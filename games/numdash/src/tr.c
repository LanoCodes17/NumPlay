#define NPAIRS ((int)(sizeof pairs / sizeof pairs[0]))

/* s may point into the middle of a longer text (the lines of a message are drawn one by one):
   the whole rest of the string is what is compared. */
const char *gfx_tr(const char *s) {
  if (!gfx_french || !s || !*s) return s;
  for (int i = 0; i < NPAIRS; i++)
    if (pairs[i].en[0] == s[0] && !strcmp(pairs[i].en, s)) return pairs[i].fr;
  return s;
}
